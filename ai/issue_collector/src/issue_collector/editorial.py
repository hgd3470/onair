"""One editorial brief shared by selection, generation and review."""
DEFAULT_AUDIENCE = {
    'audience':'40~50대 직장인',
    'interests':['고용·임금·근로 제도','대출·금리·가계 부담','세금·연금·노후 준비',
                 '주거·물가','의료·건강 정책','교육·돌봄','교통·생활 안전','국내 시장·경제 정책'],
    'weight':'공공 중요도와 검증 가능성이 비슷할 때 생활·직장 관련성을 가볍게 우선',
}


def audience_policy(config=None):
    return DEFAULT_AUDIENCE | (config or {}).get('editorial',{})


def news_brief(day, stream, config=None):
    audience=audience_policy(config)
    brief=[
        f'사건·발표 기준일은 {day.isoformat()}이다. 다음날 출근길 {audience["audience"]} 대상이다. '
        '첫 문장은 검증된 핵심 사건으로 바로 시작하고 첫 한두 문장에 실제 발표/행위 주체, 발표·사건 날짜, 무엇이 달라졌는지를 자연스럽게 연결한다. '
        '브리핑 시작 안내·인사·기준일 머리말·첫 번째 이슈라는 메타 설명 없이 완결된 뉴스 문장으로 시작한다.',
        '제목·일반 사실 문장에는 보도 매체명이나 출처 안내를 넣지 않는다. 원문 인계 v6의 승인된 의견을 인용할 때만 해당 언론사와 실제 발언자를 짧게 밝힌다. 동일 의견의 바로 이어지는 두 문장은 귀속을 공유할 수 있고 인명은 유지하며 긴 직함은 줄일 수 있다. '
        '의견을 사실로 단정하지 않고 실제 발언 주체·불확실성을 보존한다. 인용은 완전히 선택 사항이며 0~2문장이다. 사실만으로 충분하면 넣지 않는다. 인용 부재는 검토 결함이 아니다. 구체적 전망·해석을 전달하는 전했습니다/지목했습니다도 허용하며 단순 출처 안내로 거부하지 않는다. 원문 URL은 낭독하지 않는다. 실제 발표 기관·행위 주체는 유지한다.',
        '모든 문장은 합니다/했습니다/입니다/됩니다 계열의 차분한 뉴스 문체로 통일한다. 해요/했어요/죠/이에요/예요 말투를 섞지 않는다. '
        '한국시간 기준/KST 같은 시간대 안내는 낭독하지 않는다.',
        '발표일·시행일·통계 측정 기간을 구분한다. 사례 예문의 기관·날짜·통계명을 다른 사안에 복사하지 않는다. '
        '날짜는 사건에 붙여 말하고 존재하지 않는 발표 기관·시간은 만들지 않는다. 월·연도가 혼동되지 않으면 필요한 일자 중심으로 간결하게 쓴다.',
        '핵심 변화와 생활·직장에 직접 관련된 확인 사실 3~4가지를 중심으로 구성한다. 모든 카드를 읽거나 분량을 채우려 숫자·발동 요건을 나열하지 않는다. '
        '남긴 수치의 대상·단위·비교 기준은 보존한다. 근거 없는 체감 효과·개인적 조언·투자 권유·전망·청취자 행동 유도는 추가하지 않는다. 결말에서 요약을 반복하지 않는다.',
        '제목과 본문에서 발표 완료와 발표 내용의 계획·예정·실행을 구분한다. 계획 보도만으로 실행 완료 또는 미완료를 단정하지 않는다.',
        '선택한 공식 발표·제도 기준의 귀속 기관을 사실 블록에서 확인해 밝힌다. 앞 문맥에 주체가 명확하면 반복하지 않는다. '
        '보도 매체명은 발표 주체가 아니며 승인된 의견 인용 외에는 낭독하지 않는다.',
        '지수명은 코스닥 백오십·코스피 이백으로 읽고 소수부의 자리별 읽기와 구별한다. '
        '한 원소는 40자 이내 완결 문장이다. 도입에 모든 정보를 억지로 한 문장에 넣지 말고 필요하면 두 문장으로 연결한다.',
    ]
    if stream=='market':
        brief.append('국내 시장의 실제 거래일·종가/장중 구분을 유지한다. 시장 마감은 지수·거래일·주요 변동으로 바로 시작하고, '
                     '경제 통계는 실제 발표 기관·발표일·통계명/측정 월을 자연스럽게 소개한다. 고용동향을 가계대출 동향으로 바꾸지 않는다. '
                     '사이드카는 발동과 거래에 미친 확인된 효과를 우선하며 세부 발동 수식은 핵심 이해에 필요할 때만 말한다.')
    return brief
